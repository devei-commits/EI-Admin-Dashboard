// Helper function to generate date ranges
const daysAgo = (days: number): Date => {
 const date = new Date();
 date.setDate(date.getDate() - days);
 return date;
};

const monthsAgo = (months: number): Date => {
 const date = new Date();
 date.setMonth(date.getMonth() - months);
 return date;
};

